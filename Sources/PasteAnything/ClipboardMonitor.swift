import AppKit

extension NSPasteboard.PasteboardType {
    // Convención de nspasteboard.org que usan los gestores de contraseñas y otras apps.
    static let concealed = Self("org.nspasteboard.ConcealedType")
    static let transient = Self("org.nspasteboard.TransientType")
    static let autoGenerated = Self("org.nspasteboard.AutoGeneratedType")
    static let legacyTransient = Self("de.petermaurer.TransientPasteboardType")
    static let legacyOnePassword = Self("com.agilebits.onepassword")
}

/// Revisa el portapapeles periódicamente y guarda lo nuevo en el historial.
@MainActor
final class ClipboardMonitor {
    private static let pollInterval: TimeInterval = 0.5
    private static let maxImageBytes = 25 * 1024 * 1024

    private let pasteboard = NSPasteboard.general
    private let store: ClipStore
    private var lastChangeCount: Int
    private var timer: Timer?

    init(store: ClipStore) {
        self.store = store
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        let timer = Timer(timeInterval: Self.pollInterval, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.1
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    /// Evita volver a capturar lo que la propia app acaba de poner en el portapapeles.
    func markOwnWrite() {
        lastChangeCount = pasteboard.changeCount
    }

    private func poll() {
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount

        let defaults = UserDefaults.standard
        guard !defaults.bool(forKey: PreferenceKey.paused) else { return }

        let types = Set(pasteboard.types ?? [])
        guard !shouldIgnore(types, defaults: defaults) else { return }

        let app = NSWorkspace.shared.frontmostApplication
        if let bundleID = app?.bundleIdentifier, Preferences.ignoredApps.contains(bundleID) {
            return
        }

        guard let clip = readClip(types: types, app: app, defaults: defaults),
              !containsIgnoredWord(clip.text)
        else { return }

        do {
            try store.save(clip)
            try store.trim(
                keeping: max(50, defaults.integer(forKey: PreferenceKey.maxItems)),
                olderThanDays: defaults.integer(forKey: PreferenceKey.retentionDays)
            )
            if defaults.bool(forKey: PreferenceKey.playSound) {
                NSSound(named: "Tink")?.play()
            }
        } catch {
            NSLog("PasteAnything: no se pudo guardar el elemento: \(error.localizedDescription)")
        }
    }

    private func shouldIgnore(_ types: Set<NSPasteboard.PasteboardType>, defaults: UserDefaults) -> Bool {
        if defaults.bool(forKey: PreferenceKey.ignoreConcealed),
           types.contains(.concealed) || types.contains(.legacyOnePassword) {
            return true
        }
        if defaults.bool(forKey: PreferenceKey.ignoreTransient),
           types.contains(.transient) || types.contains(.legacyTransient) {
            return true
        }
        if defaults.bool(forKey: PreferenceKey.ignoreAutoGenerated), types.contains(.autoGenerated) {
            return true
        }
        return false
    }

    private func containsIgnoredWord(_ text: String?) -> Bool {
        guard let text else { return false }
        let words = Preferences.ignoredWords
        guard !words.isEmpty else { return false }
        let lowercased = text.lowercased()
        return words.contains { lowercased.contains($0) }
    }

    private func readClip(
        types: Set<NSPasteboard.PasteboardType>,
        app: NSRunningApplication?,
        defaults: UserDefaults
    ) -> NewClip? {
        let sourceApp = app?.localizedName
        let sourceBundleID = app?.bundleIdentifier

        if types.contains(.fileURL),
           let urls = pasteboard.readObjects(
               forClasses: [NSURL.self],
               options: [.urlReadingFileURLsOnly: true]
           ) as? [URL],
           !urls.isEmpty {
            guard defaults.bool(forKey: PreferenceKey.allowFiles) else { return nil }
            return NewClip(
                kind: .file,
                text: urls.map(\.path).joined(separator: "\n"),
                data: nil,
                sourceApp: sourceApp,
                sourceBundleID: sourceBundleID
            )
        }

        if let string = pasteboard.string(forType: .string),
           !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            if let rtf = pasteboard.data(forType: .rtf), defaults.bool(forKey: PreferenceKey.allowRichText) {
                return NewClip(
                    kind: .richText,
                    text: string,
                    data: rtf,
                    sourceApp: sourceApp,
                    sourceBundleID: sourceBundleID
                )
            }
            guard defaults.bool(forKey: PreferenceKey.allowText) else { return nil }
            return NewClip(
                kind: .text,
                text: string,
                data: nil,
                sourceApp: sourceApp,
                sourceBundleID: sourceBundleID
            )
        }

        if defaults.bool(forKey: PreferenceKey.allowImages),
           let png = readImageAsPNG(types: types),
           png.count <= Self.maxImageBytes {
            return NewClip(
                kind: .image,
                text: nil,
                data: png,
                sourceApp: sourceApp,
                sourceBundleID: sourceBundleID
            )
        }

        return nil
    }

    private func readImageAsPNG(types: Set<NSPasteboard.PasteboardType>) -> Data? {
        if types.contains(.png), let png = pasteboard.data(forType: .png) {
            return png
        }
        guard types.contains(.tiff), let tiff = pasteboard.data(forType: .tiff) else { return nil }
        return NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:])
    }
}
