    static let paused = "paused"
    static let ignoreConcealed = "ignoreConcealed"
    static let ignoreTransient = "ignoreTransient"
    static let ignoreAutoGenerated = "ignoreAutoGenerated"
    static let ignoredApps = "ignoredApps"
    static let ignoredWords = "ignoredWords"
    static let maxItems = "maxItems"
    static let retentionDays = "retentionDays"
    static let autoPaste = "autoPaste"
    static let alwaysPlainText = "alwaysPlainText"
    static let allowText = "allowText"
    static let allowRichText = "allowRichText"
    static let allowImages = "allowImages"
    static let allowFiles = "allowFiles"
    static let panelEdge = "panelEdge"
    static let appearance = "appearance"
    static let showInMenuBar = "showInMenuBar"
    static let previewsRichText = "previewsRichText"
    static let showsClipMenuButton = "showsClipMenuButton"
    static let playSound = "playSound"
    static let hotEdgeEnabled = "hotEdgeEnabled"
    static let hotEdgeDelay = "hotEdgeDelay"
    static let hotKey = "hotKey"
