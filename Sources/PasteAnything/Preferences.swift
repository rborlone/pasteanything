enum Preferences {
    /// Gestores de contraseñas y apps sensibles que se ignoran desde el primer uso.
    static let defaultIgnoredApps = [
        "com.apple.keychainaccess",
        "com.apple.Passwords",
        "com.1password.1password",
        "com.bitwarden.desktop",
        "org.keepassxc.keepassxc",
    ].joined(separator: "\n")

    static func register() {
        UserDefaults.standard.register(defaults: [
            PreferenceKey.paused: false,
            PreferenceKey.ignoreConcealed: true,
            PreferenceKey.ignoreTransient: true,
            PreferenceKey.ignoreAutoGenerated: true,
            PreferenceKey.ignoredApps: defaultIgnoredApps,
            PreferenceKey.ignoredWords: "",
            PreferenceKey.maxItems: 1000,
            PreferenceKey.retentionDays: 0,
            PreferenceKey.autoPaste: true,
            PreferenceKey.alwaysPlainText: false,
            PreferenceKey.allowText: true,
            PreferenceKey.allowRichText: true,
            PreferenceKey.allowImages: true,
            PreferenceKey.allowFiles: true,
            PreferenceKey.panelEdge: PanelEdge.right.rawValue,
            PreferenceKey.appearance: AppearanceMode.system.rawValue,
            PreferenceKey.showInMenuBar: true,
            PreferenceKey.previewsRichText: true,
            PreferenceKey.showsClipMenuButton: true,
            PreferenceKey.playSound: false,
            PreferenceKey.hotEdgeEnabled: false,
            PreferenceKey.hotEdgeDelay: 0.3,
            PreferenceKey.hotKey: HotKeyPreset.shiftCommandV.rawValue,
        ])
    }

    static var ignoredApps: [String] {
        get {
            let raw = UserDefaults.standard.string(forKey: PreferenceKey.ignoredApps) ?? ""
            return raw.split(whereSeparator: \.isNewline)
                .map { $0.trimmingCharacters(in: .whitespaces) }
                .filter { !$0.isEmpty }
        }
        set {
            UserDefaults.standard.set(newValue.joined(separator: "\n"), forKey: PreferenceKey.ignoredApps)
        }
    }

    static var ignoredWords: [String] {
        let raw = UserDefaults.standard.string(forKey: PreferenceKey.ignoredWords) ?? ""
        return raw.split(separator: ",")
            .map { $0.trimmingCharacters(in: .whitespaces).lowercased() }
            .filter { !$0.isEmpty }
    }
}

enum PanelEdge: String, CaseIterable, Identifiable {
    case left
    case right
    case top
    case bottom

    var id: String { rawValue }

    static var current: PanelEdge {
        PanelEdge(rawValue: UserDefaults.standard.string(forKey: PreferenceKey.panelEdge) ?? "") ?? .right
    }

    var isVertical: Bool {
        self == .left || self == .right
    }

    var title: String {
        switch self {
        case .left: "Izquierda"
        case .right: "Derecha"
        case .top: "Arriba"
        case .bottom: "Abajo"
        }
    }

    var symbol: String {
        switch self {
        case .left: "rectangle.lefthalf.inset.filled"
        case .right: "rectangle.righthalf.inset.filled"
        case .top: "rectangle.tophalf.inset.filled"
        case .bottom: "rectangle.bottomhalf.inset.filled"
        }
    }

    var closeSymbol: String {
        switch self {
        case .left: "chevron.left"
        case .right: "chevron.right"
        case .top: "chevron.up"
        case .bottom: "chevron.down"
        }
    }
}

enum AppearanceMode: String, CaseIterable, Identifiable {
    case system
    case light
    case dark

    var id: String { rawValue }

    static var current: AppearanceMode {
        AppearanceMode(rawValue: UserDefaults.standard.string(forKey: PreferenceKey.appearance) ?? "") ?? .system
    }

    var title: String {
        switch self {
        case .system: "Sistema"
        case .light: "Claro"
        case .dark: "Oscuro"
        }
    }

    @MainActor
    func apply() {
        switch self {
        case .system: NSApp.appearance = nil
        case .light: NSApp.appearance = NSAppearance(named: .aqua)
        case .dark: NSApp.appearance = NSAppearance(named: .darkAqua)
        }
    }
}

enum HotKeyPreset: String, CaseIterable, Identifiable {
    case shiftCommandV
    case optionCommandV
    case controlCommandV
    case controlOptionV
    case shiftCommandC

    var id: String { rawValue }

    static var current: HotKeyPreset {
        HotKeyPreset(rawValue: UserDefaults.standard.string(forKey: PreferenceKey.hotKey) ?? "") ?? .shiftCommandV
    }

    var title: String {
        switch self {
        case .shiftCommandV: "⇧⌘V"
        case .optionCommandV: "⌥⌘V"
        case .controlCommandV: "⌃⌘V"
        case .controlOptionV: "⌃⌥V"
        case .shiftCommandC: "⇧⌘C"
        }
    }

    var keyCode: UInt32 {
        self == .shiftCommandC ? UInt32(kVK_ANSI_C) : UInt32(kVK_ANSI_V)
    }

    var modifiers: UInt32 {
        switch self {
        case .shiftCommandV, .shiftCommandC: UInt32(cmdKey | shiftKey)
        case .optionCommandV: UInt32(cmdKey | optionKey)
        case .controlCommandV: UInt32(cmdKey | controlKey)
        case .controlOptionV: UInt32(controlKey | optionKey)
        }
    }
}

